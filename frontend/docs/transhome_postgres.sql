CREATE SCHEMA IF NOT EXISTS transhome;
SET search_path TO transhome;

-- Fungsi untuk auto-update kolom updated_at (pengganti ON UPDATE CURRENT_TIMESTAMP di MySQL)
CREATE OR REPLACE FUNCTION transhome.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

