-- ================= TRIGGER updated_at =================
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'users','roles','menus','permissions','member_profiles',
        'categories','brands','rooms','products',
        'banners','articles','site_settings','qontak_contacts'
    ] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON transhome.%1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON transhome.%1$I
                        FOR EACH ROW EXECUTE FUNCTION transhome.set_updated_at()', t);
    END LOOP;
END $$;

